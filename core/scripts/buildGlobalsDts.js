const fs = require("fs");
const path = require("path");

const coreDir = path.resolve(__dirname, "..");
const compiledAmbient = path.resolve(coreDir, "build/types/ambientGlobals.d.ts");
const bundledDts = path.resolve(coreDir, "dist/types/tripwire.d.ts");
const globalsDts = path.resolve(coreDir, "dist/types/globals.d.ts");

// Emits the opt-in ambient globals as their own declaration file, `dist/types/globals.d.ts`,
// which the published root `globals.d.ts` re-exports as `@nevware21/tripwire/globals`.
//
// The block is *not* merged into dist/types/tripwire.d.ts on purpose: `@types/mocha`,
// `@types/jest` and `@types/jasmine` declare the same global names with their own types, and
// TypeScript merges every ambient declaration in a program, so a global declared by the main
// `types` entry would break any project that also has one of those installed (TS2403/TS6200).
// Keeping it separate means importing `@nevware21/tripwire` is always clash-free and consumers
// opt in to the globals via tsconfig `types`, a `/// <reference types>`, or the
// `@nevware21/tripwire-globals` package.
//
// api-extractor's dtsRollup only bundles index.ts's own *exports*, so a `declare global` block
// would be dropped from the rollup regardless -- src/ambientGlobals.ts is compiled to
// build/types/ambientGlobals.d.ts and lifted from there, so the names and signatures have a
// single source of truth in src/ambientGlobals.ts.
function main() {
    if (!fs.existsSync(compiledAmbient)) {
        throw new Error(
            "Missing compiled declarations: " + compiledAmbient +
            "\nRun the main build (`npm run build`) first."
        );
    }

    if (!fs.existsSync(bundledDts)) {
        throw new Error(
            "Missing bundled type declarations: " + bundledDts +
            "\nRun `npm run dtsgen` first."
        );
    }

    // Anchored to the start of a line so that a mention of "declare global" inside a doc comment
    // cannot be mistaken for the declaration itself.
    const DECLARE_GLOBAL_REGEX = /^declare global\s*\{/m;

    const ambientSource = fs.readFileSync(compiledAmbient, "utf8");
    const declareGlobalMatch = DECLARE_GLOBAL_REGEX.exec(ambientSource);
    if (!declareGlobalMatch) {
        throw new Error("Expected a 'declare global' block in " + compiledAmbient);
    }

    const declareGlobalIndex = declareGlobalMatch.index;
    let globalBlockEnd = ambientSource.indexOf("\n}", declareGlobalIndex);
    globalBlockEnd = globalBlockEnd === -1 ? ambientSource.length : globalBlockEnd + 2;
    const globalBlock = ambientSource.slice(declareGlobalIndex, globalBlockEnd);

    // Guard the property that makes the main entry safe to import alongside another framework's
    // types -- if a future change ever leaks the ambient block into the rollup, fail the build
    // here rather than shipping a package that cannot compile next to @types/mocha.
    const bundled = fs.readFileSync(bundledDts, "utf8");
    if (DECLARE_GLOBAL_REGEX.test(bundled)) {
        throw new Error(
            "dist/types/tripwire.d.ts declares ambient globals.\n" +
            "The main 'types' entry must stay free of them so that importing @nevware21/tripwire\n" +
            "cannot clash with @types/mocha, @types/jest or @types/jasmine."
        );
    }

    const header = [
        "/*",
        " * @nevware21/tripwire",
        " * https://github.com/nevware21/tripwire",
        " *",
        " * Copyright (c) 2026 NevWare21 Solutions LLC",
        " * Licensed under the MIT license.",
        " */",
        "",
        "// Generated by scripts/buildGlobalsDts.js from src/ambientGlobals.ts -- do not edit.",
        "//",
        "// Opt-in ambient declarations for the bare global names a tripwire run installs. Reached",
        "// as \"@nevware21/tripwire/globals\" via the package root globals.d.ts.",
        "",
        "import { TripwireGlobals } from \"./tripwire\";",
        ""
    ].join("\n");

    fs.writeFileSync(globalsDts, header + "\n" + globalBlock + "\nexport { };\n");
    console.log("\x1b[32mWrote opt-in ambient global declarations to dist/types/globals.d.ts\x1b[0m");
}

main();
